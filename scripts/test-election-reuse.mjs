import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { loadElectionConfig, projectRoot } from "./election-config.mjs";
import { validateElectionContract } from "./election-contract.mjs";
const read = file => JSON.parse(fs.readFileSync(path.join(projectRoot,file),"utf8"));
const config = loadElectionConfig("fixtures/elections/2030/config.json");
const data = read(config.dataset), content = read(config.content);
assert.equal(validateElectionContract(data,content,config),true);
const rejects = mutate => { const changed=structuredClone(data); mutate(changed); assert.throws(()=>validateElectionContract(changed,content,config)); };
rejects(d=>d.contractVersion="2.0.0");
rejects(d=>d.candidates.push(d.candidates[0]));
rejects(d=>d.candidacies[0].candidateId="unknown");
rejects(d=>d.candidacies[0].affiliationId=d.affiliations[1].affiliationId);
rejects(d=>d.candidacies[0].electionCycle=2026);
rejects(d=>d.election.dateIso="2030-02-30");
rejects(d=>d.affiliations[0].evidenceType="ballot-party");
rejects(d=>d.affiliations[0].verifiedDate=null);
rejects(d=>d.affiliations[2].verificationState="Verified");
rejects(d=>d.results[0].votes=-1);
rejects(d=>d.results[0].candidacyId="unknown");
const env={...process.env,ELECTION_CONFIG:"fixtures/elections/2030/config.json",ELECTION_OUTPUT:"work/fixture-public"};
const currentManifest=fs.readFileSync(path.join(projectRoot,"public/build-manifest.json"));
assert.throws(()=>execFileSync(process.execPath,["scripts/build-site.mjs"],{cwd:projectRoot,env:{...env,ELECTION_OUTPUT:"public"},stdio:"pipe"}));
execFileSync(process.execPath,["scripts/build-election.mjs"],{cwd:projectRoot,env,stdio:"pipe"});
const published=read("work/fixture-public/data/election-directory-2030.json");
assert.equal(published.electionId,config.electionId);
assert.equal(published.offices.length,2);
assert.equal(published.categorySummaries.reduce((n,c)=>n+c.currentCandidateCount,0),3);
const candidates=published.offices.flatMap(o=>o.candidates);
assert.equal(candidates.length,4);
assert.equal(candidates.filter(c=>c.electionStageGroup==="primary-history").length,1);
assert.deepEqual(new Set(candidates.map(c=>c.affiliationEvidenceLabel)),new Set(["Registered affiliation","Ballot party","Primary participation",null]));
assert.equal(candidates.find(c=>c.name==="Casey Example").affiliation,"Affiliation not yet verified");
const html=fs.readFileSync(path.join(projectRoot,"work/fixture-public/index.html"),"utf8");
assert.match(html,/Tuesday, November 5, 2030/);
assert.doesNotMatch(html,/2026|Gage County/);
assert.doesNotMatch(JSON.stringify(published),/2026|Gage County|manualReview/);
const calendar=fs.readFileSync(path.join(projectRoot,"work/fixture-public/assets/example-election-2030.ics"),"utf8");
assert.match(calendar,/UID:2030-example-general@local-civic-reference/);
assert.match(calendar,/DTSTART;VALUE=DATE:20301105/);
assert.match(calendar,/DTEND;VALUE=DATE:20301106/);
assert.deepEqual(fs.readFileSync(path.join(projectRoot,"public/build-manifest.json")),currentManifest);
console.log("Election reuse passed: isolated second publication, calendar, counts, evidence distinctions, and invalid-input rejection.");
